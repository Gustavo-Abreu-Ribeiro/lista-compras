create or replace function public.app_record_item_link_price()
returns trigger
language plpgsql
set search_path = public
as $$
declare should_record boolean;
begin
  if tg_op = 'INSERT' then
    should_record := true;
  else
    should_record := new.price is distinct from old.price;
  end if;

  if new.price is not null and should_record then
    insert into public.app_item_link_price_history(owner_id, item_link_id, price, observed_at)
    values (new.owner_id, new.id, new.price, coalesce(new.last_checked_at, new.created_at, now()))
    on conflict (owner_id, item_link_id, price, observed_at) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists app_item_link_price_history_trigger on public.app_item_links;
create trigger app_item_link_price_history_trigger
after insert or update of price on public.app_item_links
for each row execute function public.app_record_item_link_price();

