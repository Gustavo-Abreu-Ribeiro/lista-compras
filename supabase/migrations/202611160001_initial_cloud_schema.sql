do $$
declare table_name text;
begin
  foreach table_name in array array[
    'app_categories','app_items','app_item_links','app_item_link_price_history',
    'app_financial_accounts','app_financial_categories','app_financial_transactions',
    'app_financial_installments','app_financial_goals','app_financial_budgets',
    'app_financial_recurrences','app_financial_debts','app_games','app_data_imports'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on public.%I from anon', table_name);
    execute format('grant select, insert, update, delete on public.%I to authenticated', table_name);
    execute format('drop policy if exists %I on public.%I', table_name || '_owner_access', table_name);
    execute format('create policy %I on public.%I for all to authenticated using ((select auth.uid()) = owner_id) with check ((select auth.uid()) = owner_id)', table_name || '_owner_access', table_name);
  end loop;
end $$;

grant usage, select on all sequences in schema public to authenticated;

create or replace function public.app_mark_financial_installment_paid(p_installment_id bigint)
returns void
language plpgsql
set search_path = public
as $$
declare installment_row public.app_financial_installments%rowtype;
begin
  select * into installment_row
  from public.app_financial_installments
  where id = p_installment_id and owner_id = (select auth.uid())
  for update;

  if not found then raise exception 'Parcela não encontrada'; end if;
  if installment_row.state <> 'pending' then raise exception 'Esta parcela já foi marcada como paga'; end if;

  insert into public.app_financial_transactions
    (uuid, owner_id, kind, amount_cents, occurred_on, description, category_id, account_id, status, installment_id)
  values
    (gen_random_uuid(), (select auth.uid()), 'expense', installment_row.amount_cents,
     installment_row.due_on, 'Parcela: ' || installment_row.description,
     installment_row.category_id, installment_row.account_id, 'posted', installment_row.id);

  update public.app_financial_installments set state = 'paid'
  where id = installment_row.id and owner_id = (select auth.uid());
end;
$$;

create or replace function public.app_create_financial_debt(
  p_name text,
  p_balance_cents bigint,
  p_monthly_payment_cents bigint,
  p_due_day integer,
  p_start_month text
)
returns void
language plpgsql
set search_path = public
as $$
begin
  insert into public.app_financial_debts
    (uuid, owner_id, name, balance_cents, monthly_payment_cents, due_day)
  values
    (gen_random_uuid(), (select auth.uid()), trim(p_name), p_balance_cents,
     p_monthly_payment_cents, p_due_day);

  if p_monthly_payment_cents > 0 then
    insert into public.app_financial_recurrences
      (uuid, owner_id, kind, description, amount_cents, day_of_month, start_month, active)
    values
      (gen_random_uuid(), (select auth.uid()), 'expense',
       'Pagamento da dívida: ' || trim(p_name), p_monthly_payment_cents,
       p_due_day, p_start_month, true);
  end if;
end;
$$;

